def render_unsloth_script(plan: TrainPlan, *, model_name: str) -> str:
    dpo_block = f'''
# ---- Stage 2: DPO on human preference pairs ({plan.dpo_train} pairs) ----
from trl import DPOConfig, DPOTrainer

dpo_dataset = load_dataset("json", data_files={{
    "train": str(DATASET / "dpo_train.jsonl"),
    "eval": str(DATASET / "dpo_eval.jsonl"),
}})

dpo_trainer = DPOTrainer(
    model=model,
    args=DPOConfig(
        output_dir=str(OUT / "dpo"),
        per_device_train_batch_size=1,
        gradient_accumulation_steps=8,
        num_train_epochs=1,
        learning_rate=5e-6,
        beta=0.1,
        max_length=1024,
        logging_steps=5,
        bf16=False, fp16=True,
    ),
    train_dataset=dpo_dataset["train"],
    eval_dataset=dpo_dataset["eval"],
    processing_class=tokenizer,
)
dpo_trainer.train()
''' if plan.run_dpo else "\n# DPO stage disabled: not enough preference pairs yet.\n"

    return f'''#!/usr/bin/env python3
"""QLoRA fine-tune for the campaign engine — generated by `lab train-kit`.

Run ON THE 3080 MACHINE (needs CUDA):
    pip install unsloth trl datasets
    python train_{model_name}.py
"""
from pathlib import Path

from datasets import load_dataset
from unsloth import FastLanguageModel

DATASET = Path({json.dumps(plan.dataset_dir)})
OUT = Path("runs/{model_name}")

model, tokenizer = FastLanguageModel.from_pretrained(
    model_name={json.dumps(plan.base_model)},
    max_seq_length=1024,
    load_in_4bit=True,
)
model = FastLanguageModel.get_peft_model(
    model, r=16, lora_alpha=32, lora_dropout=0.0,
    target_modules=["q_proj", "k_proj", "v_proj", "o_proj",
                    "gate_proj", "up_proj", "down_proj"],
)

dataset = load_dataset("json", data_files={{
    "train": str(DATASET / "sft_train.jsonl"),
    "eval": str(DATASET / "sft_eval.jsonl"),
}})

def to_text(row):
    return {{"text": tokenizer.apply_chat_template(
        row["messages"], tokenize=False, add_generation_prompt=False)}}

dataset = dataset.map(to_text)

from trl import SFTConfig, SFTTrainer

trainer = SFTTrainer(
    model=model,
    tokenizer=tokenizer,
    train_dataset=dataset["train"],
    eval_dataset=dataset["eval"],
    dataset_text_field="text",
    args=SFTConfig(
        output_dir=str(OUT / "sft"),
        per_device_train_batch_size=2,
        gradient_accumulation_steps=8,
        num_train_epochs={plan.epochs},
        learning_rate=2e-4,
        lr_scheduler_type="cosine",
        warmup_ratio=0.05,
        logging_steps=5,
        eval_strategy="epoch",
        save_strategy="epoch",
        load_best_model_at_end=True,
        max_seq_length=1024,
        bf16=False, fp16=True,
        seed=3407,
    ),
)
trainer.train()
{dpo_block}
# ---- Export: GGUF for Ollama on this same machine ----
model.save_pretrained_gguf(str(OUT / "gguf"), tokenizer,
                           quantization_method="q4_k_m")
print("GGUF written to", OUT / "gguf")
print("next: ollama create {model_name} -f Modelfile && ollama serve")
'''


def render_modelfile(plan: TrainPlan, *, model_name: str) -> str:
    return f'''# Ollama Modelfile — generated by `lab train-kit`
# ollama create {model_name} -f Modelfile
FROM ./runs/{model_name}/gguf/unsloth.Q4_K_M.gguf
PARAMETER temperature 0
PARAMETER num_ctx 4096
SYSTEM """You answer questions about one D&D campaign using only the campaign record provided. If the record does not contain the answer, reply exactly: not in the record"""
'''


def render_runbook(plan: TrainPlan, *, model_name: str) -> str:
    ready = ("READY — the dataset clears the floor."
             if plan.ready else
             "NOT READY — see warnings; collect more decisions first.")
    warning_lines = "".join(f"\n> - {w}" for w in plan.warnings) or "\n> - none"
    return f'''# Train kit — {model_name}

**Dataset:** `{plan.dataset_dir}` — {plan.sft_train} SFT train / {plan.sft_eval} eval,
{plan.dpo_train} DPO train / {plan.dpo_eval} eval. **{ready}**

> Warnings:{warning_lines}

## On the 3080 machine

1. `pip install unsloth trl datasets` (once; needs CUDA)
2. `python train_{model_name}.py` — SFT{" then DPO" if plan.run_dpo else ""},
   ~{plan.epochs} epochs, fits in 10 GB at 4-bit.
3. `ollama create {model_name} -f Modelfile && ollama serve`
   (expose it on your LAN: `OLLAMA_HOST=0.0.0.0 ollama serve`)

## Back on the main PC — prove it before it serves

```powershell
$env:TEACHERS = "local:{model_name}"
$env:LOCAL_AI_BASE_URL = "http://<3080-ip>:11434/v1"
python -m transcripts_ai.lab score --db <db> --campaign <campaign> `
    --bank bank.jsonl --answerer teacher:local --history history.jsonl
python -m transcripts_ai.lab promote --history history.jsonl `
    --candidate "teacher:local:{model_name}" --baseline memory-baseline
```

`promote` exits 0 only when the model beats the memory baseline (and its
own previous version, when one exists) on the same bank. Only then point
an engine role at it, e.g. `AI_ROLE_ANSWERER=local:{model_name}`.
'''


def write_train_kit(plan: TrainPlan, out_dir: str | Path,
                    *, model_name: str) -> list[str]:
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    files = {
        f"train_{model_name}.py": render_unsloth_script(plan, model_name=model_name),
        "Modelfile": render_modelfile(plan, model_name=model_name),
        "TRAIN_RUNBOOK.md": render_runbook(plan, model_name=model_name),
    }
    for name, content in files.items():
        (out / name).write_text(content, encoding="utf-8")
    return sorted(files)


