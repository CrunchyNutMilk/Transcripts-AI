"""Layer 4: everything the 3080 needs to train — and the promotion gate.

``train-kit`` reads a compiled dataset (Layer 3's ``sft_*.jsonl`` /
``dpo_*.jsonl``) and emits a ready-to-run training bundle for the RTX
3080 machine: an unsloth QLoRA script sized to the card and the dataset,
an Ollama ``Modelfile`` for serving the result, and a step-by-step
runbook. No training happens here — this box has no GPU; the kit is the
contract between the lab and the training machine.

``promote`` is the other half of the deal: a fine-tuned model only takes
a role in the engine when the scorecard PROVES it beats both the memory
baseline and the model it replaces, on the same question bank. The gate
is a rule, not a feeling.

Sizing defaults target an RTX 3080 (10 GB): 4-bit QLoRA on an 8B
instruct base, sequence length 1024, micro-batch 2 with gradient
accumulation. Epochs scale down as the dataset grows so small archives
do not overfit into parrots.
"""
from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path

DEFAULT_BASE_MODEL = "unsloth/Meta-Llama-3.1-8B-Instruct-bnb-4bit"
MIN_EXAMPLES_TO_TRAIN = 50
MIN_PAIRS_FOR_DPO = 40


@dataclass
class TrainPlan:
    dataset_dir: str
    base_model: str
    sft_train: int
    sft_eval: int
    dpo_train: int
    dpo_eval: int
    epochs: int
    run_dpo: bool
    warnings: list[str]

    @property
    def ready(self) -> bool:
        return self.sft_train >= MIN_EXAMPLES_TO_TRAIN


def _count_lines(path: Path) -> int:
    if not path.exists():
        return 0
    with open(path, encoding="utf-8") as f:
        return sum(1 for line in f if line.strip())


def build_plan(dataset_dir: str | Path,
               *, base_model: str = DEFAULT_BASE_MODEL) -> TrainPlan:
    dataset = Path(dataset_dir)
    sft_train = _count_lines(dataset / "sft_train.jsonl")
    sft_eval = _count_lines(dataset / "sft_eval.jsonl")
    dpo_train = _count_lines(dataset / "dpo_train.jsonl")
    dpo_eval = _count_lines(dataset / "dpo_eval.jsonl")

    # Small archives need repetition; large ones need restraint.
    if sft_train < 200:
        epochs = 4
    elif sft_train < 1000:
        epochs = 3
    else:
        epochs = 2

    warnings: list[str] = []
    if sft_train < MIN_EXAMPLES_TO_TRAIN:
        warnings.append(
            f"only {sft_train} SFT examples — below the {MIN_EXAMPLES_TO_TRAIN}"
            " floor; collect more human decisions before burning GPU hours")
    if sft_eval == 0:
        warnings.append("no SFT eval examples — the split has nothing to "
                        "measure with; do not train on this")
    run_dpo = dpo_train >= MIN_PAIRS_FOR_DPO
    if 0 < dpo_train < MIN_PAIRS_FOR_DPO:
        warnings.append(
            f"{dpo_train} DPO pair(s) is too few to shape preferences "
            f"(floor {MIN_PAIRS_FOR_DPO}); DPO stage disabled for now")
    return TrainPlan(
        dataset_dir=str(dataset), base_model=base_model,
        sft_train=sft_train, sft_eval=sft_eval,
        dpo_train=dpo_train, dpo_eval=dpo_eval,
        epochs=epochs, run_dpo=run_dpo, warnings=warnings,
    )


