# The promotion gate
# ---------------------------------------------------------------------------

@dataclass
class PromotionVerdict:
    promote: bool
    reasons: list[str]


def promotion_verdict(
    history: list[dict],
    *,
    candidate: str,
    baseline: str,
    min_lead: float = 0.02,
) -> PromotionVerdict:
    """Does the candidate's latest run earn a role?

    Rules, in order: the candidate must have a run; the baseline must
    have a run on the SAME bank size (otherwise the comparison is
    meaningless and the gate refuses rather than guesses); the candidate
    must beat the baseline by ``min_lead`` accuracy; and if the candidate
    has an earlier run on the same bank size, it must not have regressed.
    """
    def latest(name: str) -> list[dict]:
        return [h for h in history if h.get("answerer") == name]

    def accuracy(entry: dict) -> float:
        return entry["correct"] / entry["total"] if entry["total"] else 0.0

    reasons: list[str] = []
    candidate_runs = latest(candidate)
    baseline_runs = latest(baseline)
    if not candidate_runs:
        return PromotionVerdict(False, [f"no scorecard runs for {candidate!r}"])
    newest = candidate_runs[-1]
    comparable = [b for b in baseline_runs if b["total"] == newest["total"]]
    if not comparable:
        return PromotionVerdict(False, [
            f"no {baseline!r} run on the same bank size "
            f"({newest['total']} questions) — run the baseline first"])
    base = comparable[-1]
    lead = accuracy(newest) - accuracy(base)
    if lead < min_lead:
        reasons.append(
            f"candidate {accuracy(newest):.1%} vs baseline {accuracy(base):.1%}"
            f" — lead {lead:+.1%} is under the {min_lead:.0%} bar")
    previous = [c for c in candidate_runs[:-1] if c["total"] == newest["total"]]
    if previous and accuracy(newest) < accuracy(previous[-1]):
        reasons.append(
            f"regressed vs its own previous run "
            f"({accuracy(newest):.1%} < {accuracy(previous[-1]):.1%})")
    if reasons:
        return PromotionVerdict(False, reasons)
    return PromotionVerdict(True, [
        f"beats baseline by {lead:+.1%} on {newest['total']} questions"
        + (" and improved on its previous run" if previous else "")])
